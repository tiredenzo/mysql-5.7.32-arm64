SET time_zone = '+00:00';
SELECT 'CUSTOMERS';
SELECT id, HEX(label), IFNULL(email, '<NULL>') FROM customers ORDER BY id;
SELECT 'ORDERS';
SELECT id, customer_id, reference, amount, IFNULL(exchange_rate, '<NULL>'), IFNULL(HEX(note), '<NULL>'), IFNULL(HEX(payload), '<NULL>'), enabled, IFNULL(ordered_on, '<NULL>'), created_at, IFNULL(observed_at, '<NULL>'), ratio FROM orders ORDER BY id;
SELECT 'AUDIT';
SELECT id, order_id, previous_amount, new_amount FROM audit ORDER BY id;
SELECT 'VIEW';
SELECT id, HEX(label), reference, amount FROM order_summary ORDER BY id;
SELECT 'INIT';
SELECT name, executions FROM init_markers ORDER BY name;
SELECT 'ROUTINE';
CALL synthetic_count(@total);
SELECT @total;
SELECT 'OBJECTS';
SELECT TABLE_NAME, TABLE_TYPE FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() ORDER BY TABLE_NAME;
SELECT TRIGGER_NAME, EVENT_MANIPULATION, ACTION_TIMING FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = DATABASE() ORDER BY TRIGGER_NAME;
SELECT ROUTINE_NAME, ROUTINE_TYPE FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA = DATABASE() ORDER BY ROUTINE_NAME;
SELECT EVENT_NAME, STATUS, EVENT_TYPE, INTERVAL_VALUE, INTERVAL_FIELD FROM information_schema.EVENTS WHERE EVENT_SCHEMA = DATABASE() ORDER BY EVENT_NAME;
